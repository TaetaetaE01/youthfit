/**
 * 주어진 YYYY-MM-DD 가 한국 공휴일인지 반환.
 * 일요일 여부는 별도로 판단 (이 함수는 공휴일만).
 */
export function isKoreanHoliday(date: string): boolean {
  return KOREAN_HOLIDAYS.has(date);
}

/**
 * 빨강으로 표시해야 하는 날짜: 일요일 또는 공휴일.
 */
export function isRedDate(date: string): boolean {
  return new Date(date + 'T00:00:00Z').getUTCDay() === 0 || isKoreanHoliday(date);
}
